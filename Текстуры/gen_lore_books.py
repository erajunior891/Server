    g = make_base()

    # Золотые уголки
    g[3][17]='g'; g[3][18]='Y'; g[3][19]='Y'; g[3][20]='G'
    g[4][17]='G'; g[4][18]='W'; g[4][19]='Y'; g[4][20]='g'
