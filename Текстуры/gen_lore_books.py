def save_grid(filename, palette, grid):
    with open(filename, "wb") as f:
        f.write(b"[palette]\n")
        for p in palette:
            f.write(p.encode("utf-8") + b"\n")
        f.write(b"\n[grid]\n")
        for row in grid:
            f.write("".join(row).encode("utf-8") + b"\n")
    print(f"Сохранено: {filename}")

